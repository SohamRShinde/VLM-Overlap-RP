"""Inline paper/numbers.tex into the paper so the submission is a single .tex file.

    .venv/bin/python scripts/flatten_paper.py paper/paper.tex [out.tex]   # default out: paper/<name>_flat.tex

AAAI wants one .tex source (no \\input for parts of the paper), but the numbers
must stay generated by scripts/paper_numbers.py and never be retyped, by a
person or by an LLM. So the paper is drafted with a single \\input{numbers} line
and flattened here, by code, right before submission. The script refuses a
paper that already defines generated macros itself or has more than one \\input.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NUMBERS = ROOT / "paper" / "numbers.tex"
INPUT = re.compile(r"^[ \t]*\\input\{numbers(\.tex)?\}[ \t]*$", re.M)
BEGIN = "% ==== BEGIN GENERATED NUMBERS (paper/numbers.tex via scripts/paper_numbers.py; do not edit)"
END = "% ==== END GENERATED NUMBERS"


def flatten(paper: str, numbers: str) -> str:
    if len(INPUT.findall(paper)) != 1:
        raise ValueError("the paper must contain exactly one line '\\input{numbers}'")
    if re.search(r"\\(input|include)\{", INPUT.sub("", paper)):
        raise ValueError("the paper has another \\input or \\include; AAAI wants a single file")
    generated = set(re.findall(r"\\newcommand\{\\(\w+)\}", numbers))
    own = set(re.findall(r"\\newcommand\{\\(\w+)\}", paper))
    if generated & own:
        raise ValueError(f"the paper redefines generated macros: {sorted(generated & own)}")
    block = f"{BEGIN}\n{numbers.rstrip()}\n{END}"
    return INPUT.sub(lambda _: block, paper)


def main(src: str, out: str | None = None) -> Path:
    src_path = Path(src)
    out_path = Path(out) if out else src_path.with_name(src_path.stem + "_flat.tex")
    out_path.write_text(flatten(src_path.read_text(), NUMBERS.read_text()))
    print(f"{out_path}: numbers inlined from {NUMBERS.relative_to(ROOT)}")
    return out_path


if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    main(*sys.argv[1:3])
